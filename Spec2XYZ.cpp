{//data format is 380:10:730	
	const int Size = 36;
	double In[Size] = {
		380, 390, 400, 410, 420, 430, 440, 450, 460, 470,
		480, 490, 500, 510, 520, 530, 540, 550, 560, 570,
		580, 590, 600, 610, 620, 630, 640, 650, 660, 670,
		680, 690, 700, 710, 720, 730
	};

	CInterP1D Interp;
	Interp.Initial(In, spec, Size);

	double Index[SpecSize] = { 0 };
	double Spec[SpecSize] = { 0 };
	int index = 380;
	for (int i = 0; i < SpecSize; i++)
		Index[i] = (double)index++;

	Interp.Interpolation(Index, Spec, SpecSize);

	double x, y, z;
	x = y = z = 0;

	for (int i = 0; i < SpecSize; i++)
	{
		x += CIE_1931[0][i] * Spec[i];
		y += CIE_1931[1][i] * Spec[i];
		z += CIE_1931[2][i] * Spec[i];
	}
	x = x * 683.002 / 100000;
	y = y * 683.002 / 100000;
	z = z * 683.002 / 100000;
	
	//Lab : L may out of range(L > 100)
	lch.Set_XYZ(x, y, z);
}


